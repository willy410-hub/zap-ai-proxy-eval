from pydantic import BaseModel, Field
from typing import Optional

class LLMRequest(BaseModel):
    """Schema for incoming LLM requests to ensure structural validity."""
    prompt: str = Field(..., min_length=3, description="The core prompt or instruction")
    user_id: str = Field(..., description="Unique Identifier for tracing and rate limiting")
    idempotency_key: Optional[str] = Field(None, description="Key to prevent duplicate execution")

class LLMResponse(BaseModel):
    """Standardized response schema returned by the proxy layer."""
    request_id: str
    content: str
    model_used: str
    latency_ms: float
    status: str

class EvalResult(BaseModel):
    """Schema for asynchronous evaluation scores generated by LLM-as-a-Judge."""
    request_id: str
    score: float = Field(..., ge=0.0, le=1.0, description="Evaluation score between 0.0 and 1.0")
    reasoning: str
    passed_rubric: bool